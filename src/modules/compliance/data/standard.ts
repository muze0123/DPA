export type StandardChapterType = 'requirement' | 'inspection' | 'other' | 'annex';

/** 条文附图（PDF 原文插图，如图3），在条文末尾居中渲染 */
export interface StandardFigure {
  src: string;
  caption: string;
}

/** 公式项：量符号 + 可选下标（Rdf → symbol R、sub df） */
export interface StandardFormulaTerm {
  symbol: string;
  sub?: string;
}

/** 条文公式（式 9.1/9.2）：分式居中排版，右侧点线接式号；式中说明放在 textAfterFormulas */
export interface StandardFormula {
  /** 等式左侧量 */
  left: StandardFormulaTerm;
  /** 分子（单项或多项，多项以 + 连接） */
  numerator: StandardFormulaTerm[];
  /** 分母（单项或多项，多项以 + 连接） */
  denominator: StandardFormulaTerm[];
  /** 式号（9.1 / 9.2） */
  no: string;
}

/** 附表单元格：文本 + 可选跨行/跨列（表A.2「生物特征识别信息」跨行、表C.1 分组表头跨列） */
export interface StandardTableCell {
  text: string;
  rowSpan?: number;
  colSpan?: number;
}

/** 条文附表（附录 A–E 原文表格）：抽屉按表渲染，宽表（表C.1，30 列）容器横向滚动 */
export interface StandardTable {
  /** 表号与表题（如「表A.1 个人信息分类表」） */
  caption: string;
  /** 表头（可多行：表C.1 为「分组 / 列名」两级表头） */
  headers: readonly (readonly StandardTableCell[])[];
  /** 数据行；rowSpan 跨行时后续行省略被覆盖的单元格 */
  rows: readonly (readonly StandardTableCell[])[];
  /** 表注（如表A.2 注1–注3、表C.1 填写表格示例） */
  notes?: readonly string[];
}

export interface StandardNode {
  /** 条款号（6.1.1 / 附录A） */
  no: string;
  /** 所属章：4–11 或 A–E */
  chapter: string;
  kind: 'clause' | 'annex';
  title: string;
  /** 条文原文（草案版次 2026-07-03） */
  text: string;
  /** 印刷页码（PDF 页序，非纸张页序） */
  page: number;
  /** 条文附图（如 9.8.4.3.3.2 的图3）；图题不再重复写在 text 末尾 */
  figures?: readonly StandardFigure[];
  /** 条文公式（如式 9.1/9.2），渲染在 text 与 textAfterFormulas 之间 */
  formulas?: readonly StandardFormula[];
  /** 公式之后的条文（如「式中：…」变量说明） */
  textAfterFormulas?: string;
  /** 条文附表（附录 A–E 原文表格）；有附表时 text 仅存表题摘要，抽屉不重复渲染 text */
  tables?: readonly StandardTable[];
  /** 规范性附录 = true，资料性 = false */
  normative: boolean;
}

export interface StandardChapter {
  no: string;
  title: string;
  page: number;
  type: StandardChapterType;
  /** 本章入库条目数 */
  count: number;
}

