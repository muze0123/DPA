export function standardNode(no: string): StandardNode | undefined {
  return STANDARD_NODES.find((node) => node.no === no);
}

/** 平台条款目录（第 6 章 38 条）中有标准原文的条目数 */
export const STANDARD_CLAUSE_TOTAL = STANDARD_NODES.filter((node) => node.kind === 'clause' && node.chapter === '6').length;

/** 标准原文（存在则返回，供项目层「以 PDF 为准」对齐使用） */
export function standardText(no: string): string | undefined {
  return standardNode(no)?.text;
}

/** 标准原文页码（章级/条级，来源于印刷页码） */
export function standardPageOf(no: string): number | undefined {
  return standardNode(no)?.page;
}
