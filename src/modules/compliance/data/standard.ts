/**
 * 条款的章节层级路径：「6 安全技术要求 / 6.2 个人同意要求 / 6.2.1 个人同意一般要求」。
 * 只收录有标题的上级层级（章 → 二级节 → 三级及更深节），条款自身编号不入路径；
 * 附录条款的路径即「A 个人信息分类分级表」。
 */
export function sectionPathOf(node: StandardNode): string {
  const segments = node.no.split('.');
  const parts: string[] = [];
  const chapter = STANDARD_CHAPTERS.find((entry) => entry.no === node.chapter);
  if (chapter) parts.push(`${chapter.no} ${chapter.title}`);
  for (let depth = 2; depth < segments.length; depth++) {
    const prefix = segments.slice(0, depth).join('.');
    const title = standardSection(prefix)?.title ?? standardSubsection(prefix)?.title
      ?? STANDARD_NODES.find((entry) => entry.no === prefix)?.title;
    if (title) parts.push(`${prefix} ${title}`);
  }
  return parts.join(' / ');
}

