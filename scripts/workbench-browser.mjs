import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const base = process.env.DESIGN_BASE_URL || 'http://127.0.0.1:5186';
const output = 'design-report/workbench';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const issues = [];
page.on('pageerror', error => issues.push(error.message));
page.on('console', msg => { if (msg.type() === 'error' || /\[intlify\]/.test(msg.text())) issues.push(msg.text()); });
const assertions = [];
const check = (condition, label) => { assert.ok(condition, label); assertions.push(label); };
const ready = async () => { await page.locator('.task-panel').waitFor(); await page.locator('.workbench[aria-busy="false"]').waitFor(); };
try {
  await page.goto(base);
  await ready();
  check(page.url().endsWith('/workbench'), 'Root opens the workbench');
  check(await page.locator('.product-sidebar a').first().getAttribute('href') === '/workbench', 'Workbench is first in the sidebar');
  check(await page.locator('.scope-bar').count() === 0, 'Scope banner is removed');
  check(await page.locator('.overview h2').innerText() === '数据概览', 'Overview has its requested section title');
  check(/^更新时间：\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(await page.locator('.overview-updated').innerText()), 'Overview shows a full refresh timestamp');
  check(await page.locator('.task-panel h2').innerText() === '待办事项', 'Task heading uses the requested copy');
  const geometry = await page.evaluate(() => {
    const box = selector => document.querySelector(selector).getBoundingClientRect();
    const task = box('.task-panel'), side = box('.side-stack'), search = box('.task-filters .arco-input-wrapper'), select = box('.task-filters .arco-select-view');
    return { taskHeight: task.height, sideHeight: side.height, top: task.top - side.top, bottom: task.bottom - side.bottom, searchLeft: search.left, selectLeft: select.left, searchWidth: search.width, borders: [...document.querySelectorAll('.metric-card')].map(el => getComputedStyle(el).borderTopWidth) };
  });
  check(Math.abs(geometry.top) < 1 && Math.abs(geometry.bottom) < 1 && Math.abs(geometry.taskHeight - geometry.sideHeight) < 1, 'Right panels together align with the task panel');
  check(geometry.searchLeft < geometry.selectLeft && geometry.searchWidth <= 320, 'Search is left of the dropdown and constrained to 320px');
  check(geometry.borders.length === 4 && geometry.borders.every(width => width === '1px'), 'Each metric has its own bordered div');
  const total = Number(await page.locator('.metric-value').first().innerText());
  check(total > 10, 'Overview reads existing tasks');
  await page.locator('.ring-chart canvas').waitFor();
  await page.locator('.trend-chart canvas').waitFor();
  check(await page.getByText('待办汇总全平台未结束任务，按截止日期及优先级排列。', { exact: true }).count() === 0, 'Requested explanatory copy is removed');
  const chartValues = await page.evaluate(async () => {
    const url = performance.getEntriesByType('resource').map(item => item.name).find(url => url.includes('/echarts_core.js'));
    const charts = await import(url);
    const ring = charts.getInstanceByDom(document.querySelector('.ring-chart')).getOption();
    const trend = charts.getInstanceByDom(document.querySelector('.trend-chart')).getOption();
    return { ringTotal: ring.series[0].data.reduce((sum, row) => sum + row.value, 0), months: trend.xAxis[0].data.length, trendTotal: trend.series[0].data.reduce((sum, value) => sum + value, 0) };
  });
  check(chartValues.ringTotal === total, 'ECharts ring counts agree with scoped overview');
  check(chartValues.months === 12 && chartValues.trendTotal === total, 'ECharts trend uses 12 real creation-month buckets');
  await page.locator('.chart-data summary').click();
  check(await page.locator('.chart-data tbody tr').count() === 12, 'Monthly chart data is available as an accessible table');
  await page.locator('.chart-data summary').click();
  const ringBounds = await page.locator('.ring-chart').boundingBox();
  await page.mouse.click(ringBounds.x + ringBounds.width / 2 + Math.min(ringBounds.width, ringBounds.height) * 0.34, ringBounds.y + ringBounds.height / 2);
  check(await page.locator('.task-filters .arco-select-view-value').innerText() !== '待办任务', 'Clicking a ring sector filters actual tasks');
  await page.locator('.metric').first().click();
  await page.mouse.move(0, 0);
  await page.screenshot({ animations: 'disabled', path: `${output}/desktop-zh-light.png`, fullPage: true });
  await page.locator('.metric').first().click();
  check(await page.locator('.task-panel .mt-list-toolbar__summary').innerText() === `共 ${total} 项`, 'Metric and filtered count agree');
  const before = await page.locator('.task-table tbody tr').first().innerText();
  await page.locator('.task-panel .mt-pagination button').count();
  // Shared pagination uses semantic navigation buttons; verify the next page via accessible name.
  const next = page.getByRole('button', { name: '下一页', exact: true });
  await next.click();
  check(await page.locator('.task-table tbody tr').first().innerText() !== before, 'Pagination changes displayed records');
  await page.getByRole('textbox', { name: '搜索任务、功能或人员' }).fill('S-2026-0302');
  check(await page.locator('.task-table tbody tr').count() === 1, 'Search filters displayed records and resets page');
  await page.getByRole('textbox', { name: '搜索任务、功能或人员' }).fill('no-such-workbench-task');
  await page.getByText('没有匹配的任务，请调整搜索条件', { exact: true }).waitFor();
  check(true, 'No-match state is visible');
  await page.getByRole('button', { name: '查看全部任务', exact: true }).click();
  await page.locator('.attention-row').first().click();
  const overdue = Number(await page.locator('.attention-row').first().locator('span').nth(1).innerText());
  check(await page.locator('.task-panel .mt-list-toolbar__summary').innerText() === `共 ${overdue} 项`, 'Attention filters agree with their count');
  await page.locator('.stage-row').last().click();
  check(await page.locator('.task-filters .arco-select-view-value').innerText() === '已作废', 'Stage filters reflect their selected state');
  await page.locator('.metric').first().click();
  await page.locator('.task-name a').first().click();
  await page.waitForURL(/\/surveys\/S-.*\/steps\/\d+/);
  check(/\/surveys\/S-/.test(page.url()), 'Task opens actual detail route');
  await page.goBack(); await ready();
  check(page.url().endsWith('/workbench'), 'Browser back restores workbench');
  await page.goForward();
  await page.waitForURL(/\/surveys\/S-.*\/steps\/\d+/);
  check(/\/surveys\/S-/.test(page.url()), 'Browser forward restores task detail');
  await page.goBack(); await ready();
  for (const shortcut of ['/surveys', '/functions', '/sections/records', '/data-materials/materials']) {
    await page.locator(`.shortcuts a[href="${shortcut}"]`).click();
    await page.waitForURL(url => url.pathname === shortcut);
    check(new URL(page.url()).pathname === shortcut, `Shortcut opens ${shortcut}`);
    await page.goBack(); await ready();
  }
  await page.evaluate(async () => { const { useLocaleStore } = await import('/src/app/stores/locale.ts'); useLocaleStore().setLocale('en-US'); const theme = await import('/src/design/theme.ts'); theme.setThemeMode('dark'); });
  await page.getByRole('heading', { name: 'Data overview', exact: true }).waitFor();
  check(await page.locator('body').getAttribute('arco-theme') === 'dark', 'Dark theme switches live');
  await page.mouse.move(0, 0);
  await page.screenshot({ animations: 'disabled', path: `${output}/desktop-en-dark.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow English layout has no document overflow');
  check(await page.locator('.task-scroll').evaluate(el => el.scrollWidth > el.clientWidth), 'Only the task table scrolls horizontally');
  await page.mouse.move(0, 0);
  await page.screenshot({ animations: 'disabled', path: `${output}/mobile-en-dark.png`, fullPage: true });
  await page.reload(); await ready();
  check(await page.locator('.overview h2').innerText() === 'Data overview', 'Saved language survives refresh');
  await page.evaluate(async () => { const { useLocaleStore } = await import('/src/app/stores/locale.ts'); useLocaleStore().setLocale('zh-CN'); const theme = await import('/src/design/theme.ts'); theme.setThemeMode('light'); });
  await page.getByRole('heading', { name: '数据概览', exact: true }).waitFor();
  await page.mouse.move(0, 0);
  await page.screenshot({ animations: 'disabled', path: `${output}/mobile-zh-light.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  // Change the existing module identity in the isolated test context, never through product UI.
  const expected = await page.evaluate(async () => {
    const loaded = performance.getEntriesByType('resource').map(item => item.name).find(url => new URL(url).pathname === '/src/modules/surveys/data/surveys.ts');
    const data = await import(loaded || '/src/modules/surveys/data/surveys.ts');
    const policy = await import('/src/modules/workbench/data/workbench.ts');
    data.MOCK_CURRENT_USER.role = 'owner';
    return policy.visibleWorkbenchTasks(data.surveyRecords, data.MOCK_CURRENT_USER).length;
  });
  await page.locator('.shortcuts a[href="/surveys"]').click(); await page.waitForURL(url => url.pathname === '/surveys'); await page.locator('.workbench').waitFor({ state: 'detached' }); await page.locator('.product-sidebar a[href="/workbench"]').click(); await ready();

  check(await page.locator('.scope-bar').count() === 0, 'Ordinary user scope banner stays hidden');
  check(Number(await page.locator('.metric-value').first().innerText()) === expected && expected < total, 'Ordinary user overview excludes unrelated tasks');
  const scopeSafe = await page.evaluate(async () => {
    const loaded = performance.getEntriesByType('resource').map(item => item.name).find(url => new URL(url).pathname === '/src/modules/surveys/data/surveys.ts');
    const data = await import(loaded || '/src/modules/surveys/data/surveys.ts');
    const policy = await import('/src/modules/workbench/data/workbench.ts');
    const allowed = new Set(policy.visibleWorkbenchTasks(data.surveyRecords, data.MOCK_CURRENT_USER).map(r => r.id));
    return [...document.querySelectorAll('.recent-list a, .task-name a')].every(a => allowed.has(a.getAttribute('href').split('/').at(-1)));
  });
  check(scopeSafe, 'Ordinary user task list and updates remain within scope');
  await page.locator('.ring-chart canvas').waitFor();
  check(Number(await page.locator('.ring-total > span').innerText()) === expected, 'Charts follow ordinary user data scope');
  await page.mouse.move(0, 0);
  await page.screenshot({ animations: 'disabled', path: `${output}/personal-zh-light.png`, fullPage: true });
  await page.evaluate(async () => { const loaded = performance.getEntriesByType('resource').map(item => item.name).find(url => new URL(url).pathname === '/src/modules/surveys/data/surveys.ts'); const { surveyRecords } = await import(loaded || '/src/modules/surveys/data/surveys.ts'); surveyRecords.splice(0); });
  await page.getByText('暂无任务更新', { exact: true }).waitFor();
  check(Number(await page.locator('.metric-value').first().innerText()) === 0, 'Empty scope has zero metrics and empty states');
  const failureContext = await browser.newContext();
  await failureContext.addInitScript(() => { const original = indexedDB.open.bind(indexedDB); window.__restoreDb = () => { indexedDB.open = original; }; indexedDB.open = () => { throw new Error('Test storage failure'); }; });
  const failure = await failureContext.newPage();
  await failure.goto(`${base}/workbench`);
  await failure.getByRole('alert').filter({ hasText: '工作台加载失败' }).waitFor();
  check(await failure.locator('.metric').count() === 0, 'Load failure hides misleading totals');
  await failure.evaluate(() => window.__restoreDb());
  await failure.getByRole('button', { name: '重试', exact: true }).click();
  await failure.locator('.task-panel').waitFor();
  check(true, 'Retry recovers from storage failure');
  await failureContext.close();
  check(issues.length === 0, `No introduced browser errors: ${issues.join('; ')}`);
  writeFileSync(`${output}/browser.json`, JSON.stringify({ status: 'passed', assertions, issues }, null, 2));
  console.log(`Workbench browser: passed ${assertions.length} assertions`);
} finally { await browser.close(); }
